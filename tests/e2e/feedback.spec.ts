async function invitation() {
  // Fixture insertion uses the original publication so mobile regression stays unchanged.
  let { data: version } = await service.from("feedback_template_versions").select("id").eq("studio_id", studioId).eq("version", 1).maybeSingle().throwOnError();
  if (!version) {
    sql(`select private.ensure_feedback_template(${id(studioId)});`);
    version = (await service.from("feedback_template_versions").select("id").eq("studio_id", studioId).eq("version", 1).single().throwOnError()).data;
  }
  const { data } = await service.from("project_feedback").insert({ studio_id: studioId, project_id: projectId, created_by: accounts[0].id, expires_at: new Date(Date.now() + 86400000).toISOString(), template_version_id: version.id }).select("id,token").single().throwOnError();
  return data;
}
