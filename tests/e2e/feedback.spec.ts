test("scale ticks contract near the moving ring and restore after it passes", async ({ page }) => {
  const invite = await invitation();
  await locale(page);
  await page.goto(`/survey/${invite.token}`);
  const scale = page.locator('[data-feedback-scale="satisfaction"]');
  const tick = (value: number) => scale.locator(`label:has(input[value="${value}"]) [class*="tick"]`);
  const tickHeight = (value: number) => tick(value).evaluate(node => node.getBoundingClientRect().height);
  await expect.poll(() => tickHeight(3)).toBe(24);
  await scale.locator('input[value="3"]').check();
  await expect.poll(() => tickHeight(3)).toBeCloseTo(6, 1);
  await expect.poll(() => tickHeight(2)).toBe(24);
  const marker = scale.locator('[class*="markerTrack"] > span');
  const bounds = await marker.boundingBox();
  if (!bounds) throw new Error("Scale marker missing");
  const x = bounds.x + bounds.width / 2, y = bounds.y + bounds.height / 2;
  await page.mouse.move(x, y);
  await page.mouse.down();
  await page.mouse.move(x + 14, y, { steps: 6 });
  await expect.poll(() => tickHeight(3)).toBeCloseTo(15, 1);
  await page.mouse.move(x + 56, y, { steps: 6 });
  await expect.poll(() => tickHeight(3)).toBe(24);
  await page.mouse.move(x, y, { steps: 10 });
  await expect.poll(() => tickHeight(3)).toBeCloseTo(6, 1);
  await page.mouse.up();
  await scale.screenshot({ path: ".local/feedback-ring-contracting-tick.png" });
  await page.keyboard.press("ArrowRight");
  await expect(scale.locator('input[value="4"]')).toBeChecked();
  await expect.poll(() => tickHeight(3)).toBe(24);
  await expect.poll(() => tickHeight(4)).toBeCloseTo(6, 1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  const nps = page.locator('[data-feedback-scale="recommendation"]');
  await nps.locator('input[value="8"]').check();
  const selectedTick = nps.locator('label:has(input[value="8"]) [class*="tick"]');
  await expect.poll(() => selectedTick.evaluate(node => node.getBoundingClientRect().height)).toBeCloseTo(6, 1);
  await expect(selectedTick).toHaveCSS("transition-duration", "0s");
  await nps.screenshot({ path: ".local/feedback-ring-contracting-tick-mobile.png" });
});

