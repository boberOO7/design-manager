async function dragQuestion(page: Page, sourceId: string, targetId: string) {
  const source = page.locator(`[data-question-id="${sourceId}"]`);
  const target = page.locator(`[data-question-id="${targetId}"]`);
  const handle = source.getByRole("button", { name: /^Reorder question:/ });
  await target.scrollIntoViewIfNeeded();
  await handle.scrollIntoViewIfNeeded();
  const from = await handle.boundingBox(), to = await target.boundingBox();
  if (!from || !to) throw new Error("Question drag geometry missing");
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
  await page.mouse.down();
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2 - 10, { steps: 4 });
  await expect(source).toHaveAttribute("data-dragging", "true");
  await page.mouse.move(from.x + from.width / 2, to.y + to.height / 2, { steps: 14 });
  await page.mouse.up();
  await expect(source).not.toHaveAttribute("data-dragging", "true");
  await expect.poll(() => page.locator("ol > li").evaluateAll(rows => {
    const bounds = rows.map(row => row.getBoundingClientRect());
    return bounds.every((row, index) => index === 0 || row.top >= bounds[index - 1].bottom - 1);
  })).toBe(true);
}

